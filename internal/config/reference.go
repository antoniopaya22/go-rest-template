package config

import (
	"fmt"
	"strings"
)

// EnvExample renders an example environment file listing every variable.
func EnvExample() string {
	var b strings.Builder
	b.WriteString("# Generated by `make generate`. Do not edit by hand.\n")
	b.WriteString("# Copy to .env to override values locally; real environment variables win over the file.\n")

	group := ""
	for _, v := range Reference() {
		if v.Group != group {
			group = v.Group
			fmt.Fprintf(&b, "\n# --- %s ---\n", group)
		}
		fmt.Fprintf(&b, "# %s\n%s=%s\n", v.Description, v.Name, v.Default)
	}
	return b.String()
}

// Markdown renders the configuration reference as Markdown tables.
func Markdown() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `make generate`. Do not edit by hand. -->\n")
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("The application is configured with environment variables. A `.env` file in the working\n")
	b.WriteString("directory is read at startup; variables set in the real environment take precedence.\n")
	b.WriteString("Invalid values are reported together and the process exits before serving traffic.\n")

	group := ""
	for _, v := range Reference() {
		if v.Group != group {
			group = v.Group
			fmt.Fprintf(&b, "\n## %s\n\n| Variable | Default | Description |\n|---|---|---|\n", group)
		}
		fallback := "—"
		if v.Default != "" {
			fallback = "`" + v.Default + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", v.Name, fallback, v.Description)
	}
	return b.String()
}
